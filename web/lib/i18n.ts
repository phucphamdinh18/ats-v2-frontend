export const LOCALE_KEY = "ats.locale";
export function getCopy(locale: Locale): Copy {
  return locale === "en" ? en : vi;
}
export function savedLocale(value: string | null): Locale {
  return value === "en" ? "en" : "vi";
}
export function format(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(values[key] ?? `{${key}}`),
  );
}
export function jobStatusLabel(status: string, t: Copy) {
  const keys: Record<string, keyof Copy> = {
    OPEN: "statusOpen",
    DRAFT: "statusDraft",
    CLOSED: "statusClosed",
    PAUSED: "statusPaused",
    ON_HOLD: "statusPaused",
    FILLED: "statusFilled",
    CANCELLED: "statusCancelled",
  };
  return keys[status] ? t[keys[status]] : status;
}
export function roleLabel(role: string, t: Copy) {
  const keys: Record<string, keyof Copy> = {
    ADMIN: "roleAdmin",
    TA_RECRUITER: "roleTA",
    HIRING_MANAGER: "roleHM",
    INTERVIEWER: "roleInterviewer",
  };
  return keys[role] ? t[keys[role]] : role;
}
export function friendlyError(message: string, t: Copy) {
  if (Object.hasOwn(t, message)) return t[message as keyof Copy];
  if (/cấu hình kết nối/.test(message)) return t.configMissing;
  if (/URL đăng nhập/.test(message)) return t.authUrlMismatch;
  if (/quyền TA|hết hạn|JWT|unauthorized/i.test(message)) return t.scopeChanged;
  return t.requestFailed;
}
